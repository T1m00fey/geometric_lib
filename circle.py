import math


def area(r):
    """
    Вычисляет площадь круга.

    Параметры:
        r (float): радиус круга.

    Возвращает:
        float: площадь круга.

    Пример:
        area(2)  # 12.566370614359172
    """
    return math.pi * r * r


def perimeter(r):
    """
    Вычисляет длину окружности.

    Параметры:
        r (float): радиус круга.

    Возвращает:
        float: длина окружности.

    Пример:
        perimeter(2)  # 12.566370614359172
    """
    return 2 * math.pi * r